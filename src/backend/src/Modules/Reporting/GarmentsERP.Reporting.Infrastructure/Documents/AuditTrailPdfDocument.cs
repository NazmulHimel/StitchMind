namespace GarmentsERP.Reporting.Infrastructure.Documents;

using GarmentsERP.Reporting.Application.Models;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

public class AuditTrailPdfDocument : IDocument
{
    private readonly AuditTrailReportModel _model;

    public AuditTrailPdfDocument(AuditTrailReportModel model)
    {
        _model = model;
    }

    public DocumentMetadata GetMetadata() => DocumentMetadata.Default;

    public void Compose(IDocumentContainer container)
    {
        container.Page(page =>
        {
            page.Size(PageSizes.A4.Landscape());
            page.Margin(25);
            page.PageColor(Colors.White);
            page.DefaultTextStyle(x => x.FontSize(8).FontFamily("Lato"));

            page.Header().Element(ComposeHeader);
            page.Content().Element(ComposeContent);
            page.Footer().Element(ComposeFooter);
        });
    }

    private void ComposeHeader(IContainer container)
    {
        container.Row(row =>
        {
            row.RelativeItem().Column(col =>
            {
                col.Item().Text("STITCHMIND ERP - SECURITY & COMPLIANCE").Bold().FontSize(14).FontColor(Colors.Blue.Darken3);
                col.Item().Text("System Audit Trail & Security Event Dossier (SEC-05 / SEC-07)").FontSize(8).FontColor(Colors.Grey.Darken1);
                col.Item().Text($"Filter: {_model.FilterCriteria} | Generated By: {_model.GeneratedBy}").FontSize(8).FontColor(Colors.Grey.Darken1);
            });

            row.RelativeItem().AlignRight().Column(col =>
            {
                col.Item().Text("IMMUTABLE AUDIT LOG").Bold().FontSize(14).FontColor(Colors.Grey.Darken3);
                col.Item().Text($"Generated: {_model.GeneratedAt:yyyy-MM-dd HH:mm:ss} UTC").FontSize(8);
                col.Item().Text("Compliance Status: ENFORCED").Bold().FontSize(8).FontColor(Colors.Green.Darken2);
            });
        });
    }

    private void ComposeContent(IContainer container)
    {
        container.PaddingVertical(10).Table(table =>
        {
            table.ColumnsDefinition(columns =>
            {
                columns.ConstantColumn(105); // Timestamp
                columns.ConstantColumn(85);  // Entity
                columns.ConstantColumn(70);  // Action
                columns.ConstantColumn(120); // User & IP
                columns.RelativeColumn();   // Change Diff Details
            });

            table.Header(header =>
            {
                header.Cell().Background(Colors.Blue.Darken3).Padding(4).Text("TIMESTAMP (UTC)").Bold().FontColor(Colors.White);
                header.Cell().Background(Colors.Blue.Darken3).Padding(4).Text("ENTITY").Bold().FontColor(Colors.White);
                header.Cell().Background(Colors.Blue.Darken3).Padding(4).Text("ACTION").Bold().FontColor(Colors.White);
                header.Cell().Background(Colors.Blue.Darken3).Padding(4).Text("USER / IP").Bold().FontColor(Colors.White);
                header.Cell().Background(Colors.Blue.Darken3).Padding(4).Text("STATE TRANSITION & CHANGES").Bold().FontColor(Colors.White);
            });

            var isAlt = false;
            foreach (var item in _model.Items)
            {
                var bg = isAlt ? Colors.Grey.Lighten4 : Colors.White;
                isAlt = !isAlt;

                table.Cell().Background(bg).BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(4).Text($"{item.TimestampUtc:yyyy-MM-dd HH:mm:ss}");
                table.Cell().Background(bg).BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(4).Text(item.EntityName).Bold();
                
                // Color code actions
                var actionColor = item.ActionType switch
                {
                    "APPROVE" or "BUDGET_APPROVED" => Colors.Green.Darken2,
                    "DELETE" or "REJECT" => Colors.Red.Darken2,
                    "INSERT" => Colors.Blue.Darken2,
                    _ => Colors.Orange.Darken2
                };
                table.Cell().Background(bg).BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(4).Text(item.ActionType).Bold().FontColor(actionColor);

                table.Cell().Background(bg).BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(4).Column(c =>
                {
                    c.Item().Text(item.UserName).Bold();
                    c.Item().Text(item.UserIpAddress).FontSize(7).FontColor(Colors.Grey.Darken1);
                });

                table.Cell().Background(bg).BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).Padding(4).Text(item.ChangesSummary);
            }
        });
    }

    private void ComposeFooter(IContainer container)
    {
        container.Row(row =>
        {
            row.RelativeItem().Text("CONFIDENTIAL - FOR INTERNAL AUDIT & REGULATORY COMPLIANCE ONLY").FontSize(7).FontColor(Colors.Grey.Darken1);
            row.RelativeItem().AlignRight().Text(x =>
            {
                x.Span("Page ");
                x.CurrentPageNumber();
                x.Span(" of ");
                x.TotalPages();
            });
        });
    }
}
